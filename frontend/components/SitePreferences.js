'use client';

import { createContext, useContext, useEffect, useMemo, useState } from 'react';
import { usePathname } from 'next/navigation';

const SitePreferencesContext = createContext(null);

export function SitePreferencesProvider({ children }) {
  const pathname = usePathname();
  const [language, setLanguage] = useState('en');
  const [theme, setTheme] = useState('light');

  useEffect(() => {
    const savedLanguage = window.localStorage.getItem('kanak-language');
    const savedTheme = window.localStorage.getItem('kanak-theme');
    if (savedLanguage === 'en' || savedLanguage === 'hi') setLanguage(savedLanguage);
    if (savedTheme === 'light' || savedTheme === 'dark') setTheme(savedTheme);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dataset.theme = theme;
    window.localStorage.setItem('kanak-language', language);
    window.localStorage.setItem('kanak-theme', theme);
  }, [language, theme]);

  useEffect(() => {
    const titles = {
      '/': language === 'hi'
        ? 'कानक बिल्डिंग एंड मटेरियल्स | राजस्थान में गुणवत्तापूर्ण सामग्री'
        : 'Kanak Building and Materials | Quality Materials in Rajasthan',
      '/services': `${translate('Products & Services', language)} | Kanak Building and Materials`,
      '/about': `${translate('About us', language)} | Kanak Building and Materials`,
      '/contact': `${translate('Contact', language)} | Kanak Building and Materials`
    };
    document.title = titles[pathname] || titles['/'];
  }, [language, pathname]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    theme,
    setTheme,
    t: (text) => translate(text, language)
  }), [language, theme]);

  return <SitePreferencesContext.Provider value={value}>{children}</SitePreferencesContext.Provider>;
}

export function useSitePreferences() {
  const preferences = useContext(SitePreferencesContext);
  if (!preferences) throw new Error('useSitePreferences must be used within SitePreferencesProvider');
  return preferences;
}

